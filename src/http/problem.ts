/**
 * Visage RFC 9457 Problem Details for HTTP APIs (visage/http)
 *
 * Implements RFC 9457 (obsoleting RFC 7807) application/problem+json specification
 * providing a standardized machine-readable format for HTTP API error reporting.
 */

export const PROBLEM_MEDIA_TYPE = "application/problem+json";


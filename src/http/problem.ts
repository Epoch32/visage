/**
 * Lookup title / reason phrase for an HTTP status code
 */
export function getHttpStatusTitle(status: number): string {
  return HTTP_STATUS_TITLES[status] || (status >= 500 ? "Server Error" : "Client Error");
}

/**
 * Invalid parameter detail for validation errors (RFC 9457 §3.2 extension)
 */
export interface InvalidParam {
  name?: string;
  reason?: string;
  path?: string | (string | number)[];
  [key: string]: unknown;
}

/**
 * RFC 9457 Problem Details Object
 */
export interface ProblemDetails {
  /**
   * URI reference identifying the problem type (RFC 9457 §3.1.1).
   * Defaults to "about:blank".
   */
  type?: string;

  /**
   * Short, human-readable summary of the problem type (RFC 9457 §3.1.2).
   * Should not change from occurrence to occurrence of the problem.
   */
  title?: string;

  /**
   * HTTP status code generated by origin server (RFC 9457 §3.1.3).
   */
  status?: number;

  /**
   * Human-readable explanation specific to this occurrence of the problem (RFC 9457 §3.1.4).
   */
  detail?: string;

  /**
   * URI reference identifying the specific occurrence of the problem (RFC 9457 §3.1.5).
   */
  instance?: string;

  /**
   * Validation errors or invalid parameters extension (RFC 9457 §3.2).
   */
  invalidParams?: InvalidParam[];

  /**
   * Arbitrary additional problem-specific extension members.
   */
  [key: string]: unknown;
}

/**
 * Format schema validation issues into RFC 9457 invalidParams array
 */
export function formatValidationIssues(
  issues: Array<{
    path?: readonly (string | number)[] | (string | number)[] | string;
    message?: string;
  }>
): InvalidParam[] {
  return issues.map((issue) => {
    const path = Array.isArray(issue.path)
      ? [...issue.path]
      : typeof issue.path === "string"
        ? [issue.path]
        : [];
    const name = Array.isArray(issue.path) ? issue.path.join(".") : String(issue.path || "");
    const reason = issue.message || "";
    return {
      name,
      reason,
      path
    };
  });
}

/**
 * Create a Web Standard Response with RFC 9457 Problem Details JSON
 */
export function createProblemResponse(problem: ProblemDetails, init?: ResponseInit): Response {
  const status = problem.status ?? init?.status ?? 500;
  const type = problem.type ?? "about:blank";
  const title = problem.title ?? getHttpStatusTitle(status);

  const normalized: ProblemDetails = {
    type,
    title,
    status,
    ...problem
  };

  // Ensure type, title, and status are consistently set
  normalized.type = type;
  if (!problem.title) {
    normalized.title = title;
  }
  normalized.status = status;

  const headers = new Headers(init?.headers);
  headers.set("Content-Type", PROBLEM_MEDIA_TYPE);

  return new Response(JSON.stringify(normalized), {
    ...init,
    status,
    headers
  });
}

/**
 * Type guard to check if an object is an RFC 9457 ProblemDetails structure
 */
export function isProblemDetails(value: unknown): value is ProblemDetails {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    return false;
  }

  const obj = value as Record<string, unknown>;

  // Check for RFC 9457 indicators
  const hasType =
    typeof obj.type === "string" &&
    (obj.type === "about:blank" ||
      obj.type.includes("://") ||
      obj.type.startsWith("/") ||
      obj.type.startsWith("urn:"));

  const hasStatus = typeof obj.status === "number" && obj.status >= 400 && obj.status <= 599;
  const hasTitle = typeof obj.title === "string";
  const hasDetail = typeof obj.detail === "string";
  const hasInstance = typeof obj.instance === "string";
  const hasInvalidParams = Array.isArray(obj.invalidParams);

  // Must have status, or type, or title + detail, or invalidParams
  return Boolean(
    hasStatus || hasType || (hasTitle && (hasDetail || hasInstance)) || hasInvalidParams
  );
}

/**
 * Check if a Response object contains RFC 9457 Problem Details Content-Type
 */
export function isProblemResponse(response: Response): boolean {
  return Boolean(response.headers.get("Content-Type")?.includes(PROBLEM_MEDIA_TYPE));
}

/**
 * Parse an HTTP Response as RFC 9457 ProblemDetails if applicable
 */
export async function parseProblemDetails(response: Response): Promise<ProblemDetails | null> {
  try {
    const clone = response.clone();
    const data = await clone.json();
    if (isProblemDetails(data)) {
      return data;
    }
    return null;
  } catch {
    return null;
  }
}

/**
 * Error class representing an RFC 9457 Problem Detail occurrence
 */
export class ProblemError extends Error {
  readonly problem: ProblemDetails;
  readonly status: number;

  constructor(
    problemOrDetail: ProblemDetails | string,
    statusOrOptions?: number | (Partial<ProblemDetails> & { cause?: unknown })
  ) {
    let problem: ProblemDetails;
    let cause: unknown;

    if (typeof problemOrDetail === "string") {
      const opts =
        typeof statusOrOptions === "number" ? { status: statusOrOptions } : statusOrOptions || {};
      const status = opts.status ?? 500;
      cause = (opts as any).cause;
      problem = {
        type: opts.type ?? "about:blank",
        title: opts.title ?? getHttpStatusTitle(status),
        status,
        detail: problemOrDetail,
        ...opts
      };
    } else {
      const opts =
        typeof statusOrOptions === "number" ? { status: statusOrOptions } : statusOrOptions || {};
      const status = problemOrDetail.status ?? opts.status ?? 500;
      cause = (opts as any).cause;
      problem = {
        type: problemOrDetail.type ?? opts.type ?? "about:blank",
        title: problemOrDetail.title ?? opts.title ?? getHttpStatusTitle(status),
        status,
        ...problemOrDetail,
        ...opts
      };
    }

    super(problem.detail ?? problem.title ?? `HTTP ${problem.status}`, { cause });
    this.name = "ProblemError";
    this.status = problem.status ?? 500;
    this.problem = problem;
  }

  toResponse(init?: ResponseInit): Response {
    return createProblemResponse(this.problem, init);
  }
}

/**
 * Fast RFC 9457 Problem Response Factory
 */
export function problem(
  status: number,
  detail?: string,
  extra?: Record<string, unknown>,
  init?: ResponseInit
): Response {
  return createProblemResponse(
    {
      status,
      detail,
      ...extra
    },
    init
  );
}


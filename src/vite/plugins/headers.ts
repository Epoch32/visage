import * as fs from "node:fs";
import * as path from "node:path";
import { pc, type VisageLogger } from "../logger";
import type { HeadersPluginOptions, VisageVitePlugin } from "../types";

declare const process: any;

const DEFAULT_ASSETS_CACHE_CONTROL = "public, max-age=31536000, immutable";
const DEFAULT_DOCUMENT_CACHE_CONTROL = "public, max-age=0, must-revalidate";

/**
 * Parses existing _headers format into structured map of path patterns -> header entries
 */
export function parseHeadersFile(content: string): Map<string, Map<string, string>> {
  const rules = new Map<string, Map<string, string>>();
  const lines = content.split(/\r?\n/);
  let currentPath: string | null = null;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;

    // Path pattern line (not indented)
    if (!line.startsWith(" ") && !line.startsWith("\t")) {
      currentPath = trimmed;
      if (!rules.has(currentPath)) {
        rules.set(currentPath, new Map());
      }
    } else if (currentPath) {
      // Header line (indented): "Header-Name: Value"
      const colonIdx = trimmed.indexOf(":");
      if (colonIdx !== -1) {
        const name = trimmed.slice(0, colonIdx).trim();
        const value = trimmed.slice(colonIdx + 1).trim();
        rules.get(currentPath)?.set(name, value);
      }
    }
  }

  return rules;
}

/**
 * Serializes structured path rules map back into Cloudflare/Netlify _headers format
 */
export function formatHeadersFile(
  rules: Map<string, Map<string, string>>,
  comment = "Generated by Visage (RFC 9111 & RFC 8246 HTTP Standards)"
): string {
  const lines: string[] = [`# ${comment}`, ""];

  for (const [pathPattern, headers] of rules) {
    lines.push(pathPattern);
    for (const [name, value] of headers) {
      lines.push(`  ${name}: ${value}`);
    }
    lines.push("");
  }

  return `${lines.join("\n").trim()}\n`;
}

/**
 * Build-time plugin to synthesize RFC 9111 & RFC 8246 cache headers for static CDN hosting (Cloudflare, Netlify)
 */
export function createHeadersPlugin(
  options: boolean | HeadersPluginOptions | undefined,
  vLog: VisageLogger
): VisageVitePlugin {
  const isEnabled = options !== false && (typeof options !== "object" || options.enabled !== false);
  const opts = typeof options === "object" ? options : {};

  const assetsCacheControl = opts.assetsCacheControl || DEFAULT_ASSETS_CACHE_CONTROL;
  const documentCacheControl = opts.documentCacheControl || DEFAULT_DOCUMENT_CACHE_CONTROL;

  let projectRoot = typeof process !== "undefined" ? process.cwd() : ".";
  let publicDir = path.resolve(projectRoot, "public");

  return {
    name: "visage:headers",

    configResolved(config) {
      projectRoot = config.root || projectRoot;
      publicDir = config.publicDir || path.resolve(projectRoot, "public");
    },

    generateBundle(_outputOptions, bundle) {
      if (!isEnabled) return;

      // Check if user already defined an existing public/_headers file
      let existingContent = "";
      const publicHeadersPath = path.resolve(publicDir, "_headers");
      if (fs.existsSync(publicHeadersPath)) {
        try {
          existingContent = fs.readFileSync(publicHeadersPath, "utf-8");
        } catch {}
      } else if (bundle._headers && "source" in bundle._headers) {
        existingContent = String((bundle._headers as any).source || "");
      }

      const rulesMap = parseHeadersFile(existingContent);

      // 1. Ensure /assets/* has immutable cache rule (RFC 8246) unless overridden
      if (!rulesMap.has("/assets/*")) {
        const assetsHeaders = new Map<string, string>();
        assetsHeaders.set("Cache-Control", assetsCacheControl);
        rulesMap.set("/assets/*", assetsHeaders);
      } else {
        const headers = rulesMap.get("/assets/*")!;
        if (!headers.has("Cache-Control")) {
          headers.set("Cache-Control", assetsCacheControl);
        }
      }

      // 2. Ensure /* has revalidate rule (RFC 9111) unless overridden
      if (!rulesMap.has("/*")) {
        const docHeaders = new Map<string, string>();
        docHeaders.set("Cache-Control", documentCacheControl);
        rulesMap.set("/*", docHeaders);
      } else {
        const headers = rulesMap.get("/*")!;
        if (!headers.has("Cache-Control")) {
          headers.set("Cache-Control", documentCacheControl);
        }
      }

      // 3. Apply custom user rules if provided
      if (opts.customRules) {
        for (const [pathPattern, headersObj] of Object.entries(opts.customRules)) {
          if (!rulesMap.has(pathPattern)) {
            rulesMap.set(pathPattern, new Map());
          }
          const target = rulesMap.get(pathPattern)!;
          for (const [hName, hVal] of Object.entries(headersObj)) {
            target.set(hName, hVal);
          }
        }
      }

      const outputContent = formatHeadersFile(rulesMap);

      // Emit file into build output
      this.emitFile({
        type: "asset",
        fileName: "_headers",
        source: outputContent
      });

      vLog.info(
        "visage:headers",
        `Synthesized ${pc.cyan("_headers")} with RFC 8246 immutable assets and RFC 9111 revalidation`
      );
    },

    configurePreviewServer(server) {
      if (!isEnabled) return;

      server.middlewares.use((req: any, res: any, next: any) => {
        const url = req.url?.split("?")[0] || "";

        if (url.startsWith("/assets/")) {
          res.setHeader("Cache-Control", assetsCacheControl);
        } else if (
          url === "/" ||
          url.endsWith(".html") ||
          req.headers?.accept?.includes("text/html")
        ) {
          res.setHeader("Cache-Control", documentCacheControl);
        }

        next();
      });
    }
  };
}

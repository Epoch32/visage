import { execSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";
import type { ZigNativeOptions } from "./types";

/**
 * Automatically inspect Zig build error output and sync build.zig.zon fingerprint
 */
export function autoSyncZigFingerprint(projectRoot: string): void {
  const buildZonPath = path.join(projectRoot, "build.zig.zon");
  if (!fs.existsSync(buildZonPath)) return;

  try {
    execSync("zig build --help", { cwd: projectRoot, stdio: "pipe" });
  } catch (err: any) {
    const output = `${err.stderr?.toString() || ""}\n${err.stdout?.toString() || ""}`;
    const match =
      output.match(/if this is a new or forked package, use this value:\s*(0x[0-9a-fA-F]+)/) ||
      output.match(/suggested value:\s*(0x[0-9a-fA-F]+)/);

    if (match?.[1]) {
      const validFingerprint = match[1];
      let zon = fs.readFileSync(buildZonPath, "utf8");
      if (zon.includes(".fingerprint")) {
        zon = zon.replace(
          /\.fingerprint\s*=\s*0x[0-9a-fA-F]+/,
          `.fingerprint = ${validFingerprint}`
        );
      } else {
        zon = zon.replace(
          /(\.version\s*=\s*"[^"]*",?)/,
          `$1\n    .fingerprint = ${validFingerprint},`
        );
      }
      fs.writeFileSync(buildZonPath, zon, "utf8");
    }
  }
}

/**
 * Generate native Zig host project scaffolding (build.zig.zon, build.zig, src-native/main.zig)
 * with automated webview/webview bindings for Linux and cross-platform desktop compilation.
 */
export function scaffoldZigNative(projectRoot: string, options: ZigNativeOptions = {}): void {
  const title = options.title ?? "Visage Native";
  const width = options.width ?? 1024;
  const height = options.height ?? 768;
  const resizable = options.resizable !== false;
  const debug = Boolean(options.debug);
  const outputDir = path.resolve(projectRoot, options.outputDir ?? "src-native");

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // 1. Generate build.zig.zon at project root if it does not exist
  const buildZonPath = path.join(projectRoot, "build.zig.zon");
  if (!fs.existsSync(buildZonPath)) {
    const buildZonContent = `.{
    .name = .visage_app,
    .version = "0.1.0",
    .fingerprint = 0xd0d1ff8d1cf1039a,
    .dependencies = .{
        .webview = .{
            .url = "git+https://github.com/happystraw/zig-webview",
            .hash = "webview-0.1.0-mgPxHGBfKQDfUGh2sTdiuIOVrBHRtvNZE4-B8NXoEWxA",
        },
    },
    .paths = .{
        "build.zig",
        "build.zig.zon",
        "${options.outputDir ?? "src-native"}",
    },
}
`;
    fs.writeFileSync(buildZonPath, buildZonContent, "utf8");
  }

  // 2. Generate build.zig at project root if it does not exist
  const buildZigPath = path.join(projectRoot, "build.zig");
  if (!fs.existsSync(buildZigPath)) {
    const relOutputDir = options.outputDir ?? "src-native";
    const buildZigContent = `const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const exe_mod = b.createModule(.{
        .root_source_file = b.path("${relOutputDir}/main.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });

    const webview_dep = b.dependency("webview", .{
        .target = target,
        .optimize = optimize,
    });
    exe_mod.addImport("webview", webview_dep.module("webview"));

    exe_mod.addAnonymousImport("ui_html", .{
        .root_source_file = b.path("dist/index.html"),
    });

    const exe = b.addExecutable(.{
        .name = "visage-app",
        .root_module = exe_mod,
    });

    b.installArtifact(exe);

    const run_cmd = b.addRunArtifact(exe);
    run_cmd.step.dependOn(b.getInstallStep());
    if (b.args) |args| {
        run_cmd.addArgs(args);
    }

    const run_step = b.step("run", "Run the native Visage application");
    run_step.dependOn(&run_cmd.step);
}
`;
    fs.writeFileSync(buildZigPath, buildZigContent, "utf8");
  }

  // 3. Generate src-native/main.zig if it does not already exist
  const mainZigPath = path.join(outputDir, "main.zig");
  if (!fs.existsSync(mainZigPath)) {
    const mainZigContent = `//! Visage Native Application Host (Zig)
//! Generated by @epoch32/visage (experimental: { zigNative: true })

const std = @import("std");
const builtin = @import("builtin");
const Webview = @import("webview").Webview;

// Embedded frontend single-bundle HTML compiled from Visage client
const HTML_CONTENT = @embedFile("ui_html");

pub const WindowConfig = struct {
    pub const title: [:0]const u8 = "${title}";
    pub const width: c_int = ${width};
    pub const height: c_int = ${height};
    pub const resizable: bool = ${resizable};
    pub const debug: bool = ${debug};
};

var global_webview: ?*Webview = null;

fn handleNativeCall(id: [:0]const u8, req: [:0]const u8, arg: ?*anyopaque) void {
    _ = arg;
    const w = global_webview orelse return;

    if (std.mem.indexOf(u8, req, "getSystemInfo") != null) {
        var buf: [256:0]u8 = undefined;
        const os_name = @tagName(builtin.os.tag);
        const cpu_arch = @tagName(builtin.cpu.arch);
        const res = std.fmt.bufPrintZ(&buf, "{{\\"os\\": \\"{s}\\", \\"arch\\": \\"{s}\\", \\"engine\\": \\"visage-native\\"}}", .{ os_name, cpu_arch }) catch "{}";
        w.respond(id, .ok, res) catch {};
    } else if (std.mem.indexOf(u8, req, "ping") != null) {
        w.respond(id, .ok, "{\\"pong\\": true}") catch {};
    } else if (std.mem.indexOf(u8, req, "window:close") != null) {
        w.terminate() catch {};
    } else if (std.mem.indexOf(u8, req, "window:minimize") != null) {
        w.minimize() catch {};
        w.respond(id, .ok, "{}") catch {};
    } else if (std.mem.indexOf(u8, req, "window:maximize") != null) {
        w.maximize() catch {};
        w.respond(id, .ok, "{}") catch {};
    } else {
        w.respond(id, .ok, "{\\"ok\\": true}") catch {};
    }
}

pub fn main() !void {
    const w = try Webview.create(WindowConfig.debug, null);
    defer w.destroy() catch unreachable;

    global_webview = w;

    try w.setTitle(WindowConfig.title);
    try w.setSize(WindowConfig.width, WindowConfig.height, if (WindowConfig.resizable) .none else .fixed);

    // Inject native bridge marker before document evaluation
    try w.addInitScript(
        \\\\window.__visage_native = true;
        \\\\window.__visage_native_platform = "linux";
    );

    // Bind native IPC call handler
    try w.bindRaw("__visage_native_call", handleNativeCall, null);

    // Set HTML content and run desktop event loop
    try w.setHtml(HTML_CONTENT);
    try w.run();
}
`;
    fs.writeFileSync(mainZigPath, mainZigContent, "utf8");
  }

  // 4. Automatically sync and validate package fingerprint if Zig compiler is available
  autoSyncZigFingerprint(projectRoot);
}
